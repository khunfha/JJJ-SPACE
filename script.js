function createTemplateCard(src, alt, fileName) {
  const card = document.createElement("button");
  card.type = "button";
  card.className = "template-card";
  card.dataset.templateId = alt.replace(/[^a-zA-Z0-9]/g, "");

  const img = document.createElement("img");
  img.src = src;
  img.alt = alt;
  card.appendChild(img);

  const lowerFileName = fileName.toLowerCase();
  const tags = [];
  const isSecret = /-secret(?:[\w-]*)(?:[^\w]|$)/i.test(lowerFileName);
  const isSuperSecretRare = /-ssr(?:[\w-]*)(?:[^\w]|$)/i.test(lowerFileName);
  const isSuperRare = /-sr(?:[\w-]*)(?:[^\w]|$)/i.test(lowerFileName);

  if (isSuperSecretRare) {
    tags.push("SUPER SECRET RARE");
  } else if (isSuperRare) {
    tags.push("SUPER RARE");
  }

  let categoryTag = null;
  if (/-jjj(?:[\w-]*)(?:[^\w]|$)/i.test(lowerFileName)) {
    categoryTag = "JANJINGJING";
  } else if (/-jj(?:[\w-]*)(?:[^\w]|$)/i.test(lowerFileName)) {
    categoryTag = "JINGJING";
  } else if (/-jewel(?:[\w-]*)(?:[^\w]|$)/i.test(lowerFileName)) {
    categoryTag = "JEWEL";
  } else if (/-j(?:[\w-]*)(?:[^\w]|$)/i.test(lowerFileName)) {
    categoryTag = "JAN";
  }

  if (categoryTag) {
    tags.push(categoryTag);
  }

  if (isSecret) {
    tags.push("SECRET");
  }

  const uniqueTags = [...new Set(tags)];

  if (uniqueTags.length > 0) {
    const tag = document.createElement("span");
    tag.className = "template-tag";
    tag.textContent = uniqueTags[0];
    card.appendChild(tag);
    card.dataset.tag = uniqueTags[0];
    card.dataset.tags = uniqueTags.join(",");
  } else {
    card.dataset.tag = "NONE";
    card.dataset.tags = "NONE";
  }

  if (isSecret) {
    card.classList.add("secret");
  }

  card.addEventListener("click", () => {
    document.querySelectorAll(".template-card").forEach((node) => node.classList.remove("active"));
    card.classList.add("active");
  });

  return card;
}

function updateFilterButtonState(container, activeFilters) {
  container.querySelectorAll(".filter-button").forEach((node) => node.classList.remove("active"));
  if (activeFilters.includes("All")) {
    const allButton = Array.from(container.children).find((node) => node.textContent === "All");
    if (allButton) allButton.classList.add("active");
  } else {
    Array.from(container.children).forEach((node) => {
      if (activeFilters.includes(node.textContent)) {
        node.classList.add("active");
      }
    });
  }
}

function createCategoryFilterButtons() {
  filterBar.innerHTML = "";
  categoryFilterTags.forEach((tag) => {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "filter-button";
    button.textContent = tag;
    button.addEventListener("click", () => {
      if (tag === "All") {
        activeCategoryFilters = ["All"];
      } else {
        const index = activeCategoryFilters.indexOf(tag);
        if (index === -1) {
          activeCategoryFilters.push(tag);
        } else {
          activeCategoryFilters.splice(index, 1);
        }
        if (activeCategoryFilters.length === 0) {
          activeCategoryFilters = ["All"];
        } else {
          const allIndex = activeCategoryFilters.indexOf("All");
          if (allIndex !== -1) {
            activeCategoryFilters.splice(allIndex, 1);
          }
        }
      }
      filterCards();
      updateFilterButtonState(filterBar, activeCategoryFilters);
    });
    filterBar.appendChild(button);
  });

  const clearButton = document.createElement("button");
  clearButton.type = "button";
  clearButton.className = "filter-button clear-button";
  clearButton.textContent = "Clear";
  clearButton.addEventListener("click", () => {
    activeCategoryFilters = ["All"];
    filterCards();
    updateFilterButtonState(filterBar, activeCategoryFilters);
  });
  filterBar.appendChild(clearButton);
}

